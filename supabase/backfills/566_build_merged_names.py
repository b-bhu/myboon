#!/usr/bin/env python3
"""#566: build 566_merged_names.sql from the CTO's Nov 3 cleanup artifacts.

Inputs (shared computer, /workspace/proposed-cleanup):
  retired-hard-delete-backup.json  names/aliases of the hard-deleted retired entities
  batch*-apply-plan.json           applied plans (batch*-plan.json where no apply-plan exists)
  b1_*.sql                         batch 1 ran as hand SQL; its 3 merges are listed below
Only MERGE rows are emitted (loser name + loser aliases -> winner). Retired-only names are
never emitted, so they claim no (type, norm_alias). Output is a plain VALUES insert into the
staging table atlas.entity_alias_merge_source; rerunning the insert is a no-op.
"""
import glob, json, os, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/workspace/proposed-cleanup"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "566_merged_names.sql")
BATCH1 = [("binance-second-withdrawal-phase", "binance"), ("ai-coding", "ai-industry"),
          ("open-weight-models", "ai-industry")]

backup = json.load(open(os.path.join(SRC, "retired-hard-delete-backup.json")))["entities"]
by_id = {e["id"]: e for e in backup}
by_slug = {e["slug"]: e for e in backup}

merges = []  # (loser, winner_id or None, winner_slug or None, batch)
for f in sorted(glob.glob(os.path.join(SRC, "batch*-plan.json"))):
    if f.endswith("-apply-plan.json"):
        continue
    ap = f.replace("-plan.json", "-apply-plan.json")
    plan = json.load(open(ap if os.path.exists(ap) else f))
    batch = os.path.basename(f).split("-")[0]
    for r in plan:
        if r["action"] == "MERGE":
            merges.append((by_id[r["id"]], r["target_id"], None, batch))
for loser, winner in BATCH1:
    merges.append((by_slug[loser], None, winner, "batch1"))

def lit(s):
    return "null" if s is None else "'" + s.replace("'", "''") + "'"

rows = []
for e, wid, wslug, batch in merges:
    names = [e["name"], e["slug"]] + list(e.get("aliases") or [])
    seen = set()
    for n in names:
        n = (n or "").strip()
        if not n or n.lower() in seen:
            continue
        seen.add(n.lower())
        rows.append(f"  ({lit(e['id'])}::uuid, {lit(e['slug'])}, {lit(n)}, "
                    f"{lit(wid)}::uuid, {lit(wslug)}, {lit(batch)})")

with open(OUT, "w") as o:
    o.write("-- GENERATED by 566_build_merged_names.py from the Nov 3 cleanup artifacts. Do not edit.\n")
    o.write(f"-- {len(merges)} merged losers, {len(rows)} candidate names.\n")
    o.write("insert into atlas.entity_alias_merge_source\n"
            "  (loser_id, loser_slug, alias, winner_id, winner_slug, batch)\nvalues\n")
    o.write(",\n".join(rows))
    o.write("\non conflict do nothing;\n")
print(f"merges={len(merges)} names={len(rows)} -> {OUT}")
